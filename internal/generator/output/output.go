// Package output hands every pass the one companion file a proto file gets,
// so resource names and filter helpers land in a single `_aip.pb.go`.
package output

import "google.golang.org/protobuf/compiler/protogen"

// Suffix is `_aip.pb.go`. The leading `_` (0x5F) sorts after `.` (0x2E), so
// `<name>.pb.go` always initialises before our companion — descriptor init
// runs before our `init()`. It is also the `_<plugin>.pb.go` shape
// protoc-gen-go-grpc uses.
const Suffix = "_aip.pb.go"

// Files tracks the companion of each proto file across passes.
type Files struct {
	plugin *protogen.Plugin
	byFile map[*protogen.File]*protogen.GeneratedFile
}

// New returns a Files that creates companions on plugin.
func New(plugin *protogen.Plugin) *Files {
	return &Files{
		plugin: plugin,
		byFile: map[*protogen.File]*protogen.GeneratedFile{},
	}
}

// Open returns f's companion, creating it — header included — on first use.
// A pass calls it only once it has something to emit, so a file no pass
// writes to is never generated.
func (fs *Files) Open(f *protogen.File) *protogen.GeneratedFile {
	if g, ok := fs.byFile[f]; ok {
		return g
	}
	g := fs.plugin.NewGeneratedFile(f.GeneratedFilenamePrefix+Suffix, f.GoImportPath)
	g.P("// Code generated by protoc-gen-go-aip. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	fs.byFile[f] = g
	return g
}
